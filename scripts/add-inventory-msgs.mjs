function deepMerge(base, extra) {
  for (const [k, v] of Object.entries(extra)) {
    if (v && typeof v === 'object' && !Array.isArray(v)) {
      base[k] = deepMerge(base[k] && typeof base[k] === 'object' ? base[k] : {}, v);
    } else {
      base[k] = v;
    }
  }
  return base;
}

for (const [file, patch] of [['messages/en.json', EN], ['messages/ar.json', AR]]) {
  const messages = JSON.parse(readFileSync(file, 'utf8'));
  deepMerge(messages, { inventory: patch });
  writeFileSync(file, JSON.stringify(messages, null, 2) + '\n');
  console.log(`${file}: inventory namespace now has ${Object.keys(messages.inventory).length} top-level keys`);
}
